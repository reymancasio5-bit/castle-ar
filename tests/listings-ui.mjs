import assert from 'node:assert/strict';
import {createServer} from 'vite';
import React from 'react';
import {act,create} from 'react-test-renderer';
import {renderToStaticMarkup} from 'react-dom/server';
const server=await createServer({server:{middlewareMode:true},appType:'custom'});
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
globalThis.window={addEventListener(){},removeEventListener(){}};
try{
 const {default:Listings}=await server.ssrLoadModule('/src/ListingsPage.tsx');
 const {createPreviewApi}=await server.ssrLoadModule('/src/preview-api.ts');
 const api=createPreviewApi();let snapshot=await api.read();
 const listing={id:'ui-listing',name:'Independent House',managerId:snapshot.managers[0].id};
 snapshot=await api.save(snapshot.revision,[{kind:'saveListing',listing,ownerId:''}]);
 let changes,imported,tree;
 const props={snapshot,monthId:snapshot.months[0].id,onDirtyChange:()=>{},onSave:async(revision,value)=>{changes=value;},onImport:(l,m,options)=>{imported={l,m,options};}};
 const html=renderToStaticMarkup(React.createElement(Listings,props));
 assert.ok(html.includes('Independent House'));assert.ok(html.includes('Not Added Yet'));
 await act(async()=>{tree=create(React.createElement(Listings,props));});
 const button=text=>tree.root.findAllByType('button').find(b=>b.children.includes(text));
 await act(async()=>button('Add Listing').props.onClick());
 assert.ok(!tree.root.findAllByType('input').some(i=>i.props.inputMode==='decimal'),'listing creation must not ask for amount');
 const name=tree.root.findAllByType('input').find(i=>i.props.placeholder==='e.g. Castle Beach House');
 await act(async()=>name.props.onChange({target:{value:'Brand New Listing'}}));
 await act(async()=>tree.root.findByType('form').props.onSubmit({preventDefault(){}}));
 assert.equal(changes[0].kind,'saveListing');assert.equal(changes[0].listing.name,'Brand New Listing');assert.ok(!('totalCents' in changes[0]));
 const row=()=>tree.root.findAllByType('tr').find(r=>r.findAllByType('span').some(s=>s.children.includes('Independent House')));
 await act(async()=>row().findAllByType('button').find(b=>b.children.includes('Add To Month')).props.onClick());
 const amount=tree.root.findAllByType('input').find(i=>i.props.inputMode==='decimal');
 await act(async()=>amount.props.onChange({target:{value:'123.45'}}));
 await act(async()=>tree.root.findByType('form').props.onSubmit({preventDefault(){}}));
 assert.equal(changes[0].kind,'addProperty');assert.equal(changes[0].name,'Independent House');assert.equal(changes[0].totalCents,12345);assert.equal(changes[0].monthId,props.monthId);
 await act(async()=>row().findAllByType('button').find(b=>b.children.includes('Add To Month')).props.onClick());
 const managerSelect=tree.root.findAllByType('select').find(s=>s.props['aria-label']==='Account Manager');
 await act(async()=>managerSelect.props.onChange({target:{value:snapshot.managers[1].name}}));
 await act(async()=>button('Import File').props.onClick());
 assert.equal(imported.options.manager,snapshot.managers[1].name);assert.equal(imported.l.name,'Independent House');assert.equal(imported.m.id,props.monthId);
 await act(async()=>tree.unmount());
 const anotherMonth={id:'other-month',label:'Other Month',month:'2027-01',properties:[{id:'other-property',name:listing.name,manager:snapshot.managers[0].name,managerId:listing.managerId,totalCents:50000,payments:[]}]};
 await act(async()=>{tree=create(React.createElement(Listings,{...props,snapshot:{...snapshot,months:[...snapshot.months,anotherMonth]}}));});
 await act(async()=>row().findAllByType('button').find(b=>b.children.includes('Add To Month')).props.onClick());
 await act(async()=>tree.root.findAllByType('input').find(i=>i.props.inputMode==='decimal').props.onChange({target:{value:'100'}}));
 await act(async()=>tree.root.findAllByType('select').find(s=>s.props.value===props.monthId).props.onChange({target:{value:anotherMonth.id}}));
 await act(async()=>button('Import File').props.onClick());
 assert.equal(imported.options.total,'500.00','switching months must preserve the existing expected amount');
 await act(async()=>tree.unmount());
 const emptyMonths=renderToStaticMarkup(React.createElement(Listings,{...props,snapshot:{...snapshot,months:[]}}));assert.ok(emptyMonths.includes('Independent House'));
 console.log('Listings UI: amount-free creation, directory without months, monthly amount, and import handoff passed.');
}finally{await server.close();}
